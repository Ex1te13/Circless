"""Storage of circles (video notes), tags and per-user state.

Works on Postgres (Supabase, production) and SQLite (tests). SQL is written once with
"?" placeholders and only features both databases share; ids come back via RETURNING.
The video itself stays on Telegram's servers / Supabase Storage, we keep its file_id.
"""
import sqlite3
import time
from typing import Any

from core import timing

SCHEMA = """
CREATE TABLE IF NOT EXISTS batches (
    id         {ID},
    user_id    BIGINT NOT NULL,
    created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS circles (
    id             {ID},
    user_id        BIGINT  NOT NULL,
    file_id        TEXT    NOT NULL,
    file_unique_id TEXT    NOT NULL,
    duration       INTEGER,
    orig_date      BIGINT,           -- when the circle was originally recorded/sent
    added_at       BIGINT  NOT NULL,
    batch_id       BIGINT REFERENCES batches(id) ON DELETE SET NULL,
    thumb_file_id  TEXT,
    stored_video   INTEGER NOT NULL DEFAULT 0,   -- already copied to Supabase Storage
    stored_thumb   INTEGER NOT NULL DEFAULT 0,
    UNIQUE (user_id, file_unique_id)
);
CREATE TABLE IF NOT EXISTS tags (
    id      {ID},
    user_id BIGINT NOT NULL,
    name    TEXT   NOT NULL,
    UNIQUE (user_id, name)
);
CREATE TABLE IF NOT EXISTS circle_tags (
    circle_id BIGINT NOT NULL REFERENCES circles(id) ON DELETE CASCADE,
    tag_id    BIGINT NOT NULL REFERENCES tags(id)    ON DELETE CASCADE,
    PRIMARY KEY (circle_id, tag_id)
);
CREATE INDEX IF NOT EXISTS idx_circle_tags_tag ON circle_tags(tag_id);
-- messages in the bot chat, so they can be cleaned up later
CREATE TABLE IF NOT EXISTS chat_messages (
    chat_id    BIGINT NOT NULL,
    message_id BIGINT NOT NULL,
    grp        TEXT,                 -- id of the circle listing the message belongs to
    sent_at    BIGINT NOT NULL,
    PRIMARY KEY (chat_id, message_id)
);
-- everything the bot has to remember between messages (each webhook call is a fresh start)
CREATE TABLE IF NOT EXISTS user_state (
    user_id       BIGINT PRIMARY KEY,
    newest_first  INTEGER NOT NULL DEFAULT 0,
    cur_target    TEXT,      -- what typed tags apply to: "b<batch>" or "c<circle>"
    cur_chat      BIGINT,
    cur_msg       BIGINT,    -- the tagging prompt message
    open_batch    BIGINT,    -- batch that newly forwarded circles join
    open_batch_at BIGINT
);
"""
ID_SQLITE = "INTEGER PRIMARY KEY AUTOINCREMENT"
ID_PG = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
STATE_FIELDS = ("newest_first", "cur_target", "cur_chat", "cur_msg", "open_batch", "open_batch_at")
TABLES = ("batches", "circles", "tags", "circle_tags", "chat_messages", "user_state")


def normalize_tag(name: str) -> str:
    return " ".join(name.strip().lstrip("#").split()).lower()


class DB:
    def __init__(self, url: str):
        self.url = url
        self.pg = url.startswith(("postgres://", "postgresql://"))
        self.conn: Any = None
        self._connect()
        self.init_schema()

    # ---------- low level ----------
    def _connect(self) -> None:
        if self.pg:
            import psycopg
            from psycopg.rows import dict_row

            # prepare_threshold=None: Supabase's transaction pooler can't keep prepared statements
            self.conn = psycopg.connect(self.url, autocommit=True, prepare_threshold=None, row_factory=dict_row)
        else:
            self.conn = sqlite3.connect(self.url, isolation_level=None, check_same_thread=False)  # autocommit
            self.conn.row_factory = sqlite3.Row
            self.conn.execute("PRAGMA foreign_keys = ON")

    def _sql(self, sql: str) -> str:
        return sql.replace("?", "%s") if self.pg else sql

    def ex(self, sql: str, params: tuple | list = ()):
        t0 = time.perf_counter()
        try:
            return self._ex(sql, params)
        finally:
            timing.add("db", time.perf_counter() - t0)

    def _ex(self, sql: str, params: tuple | list = ()):
        try:
            return self.conn.execute(self._sql(sql), params)
        except Exception as e:
            # serverless instances sleep; a dropped Postgres connection is reopened once
            if self.pg and type(e).__name__ in ("OperationalError", "InterfaceError"):
                self._connect()
                return self.conn.execute(self._sql(sql), params)
            raise

    def many(self, sql: str, rows: list) -> None:
        if not rows:
            return
        if self.pg:
            with self.conn.cursor() as cur:
                cur.executemany(self._sql(sql), rows)
        else:
            self.conn.executemany(sql, rows)

    def one(self, sql: str, params: tuple | list = ()):
        return self.ex(sql, params).fetchone()

    def all(self, sql: str, params: tuple | list = ()) -> list:
        return self.ex(sql, params).fetchall()

    def init_schema(self) -> None:
        script = SCHEMA.replace("{ID}", ID_PG if self.pg else ID_SQLITE)
        if self.pg:
            # no parameters → simple query protocol, which allows several statements at once
            self.conn.execute(script)
        else:
            self.conn.executescript(script)

    def ping(self) -> None:
        self.one("SELECT 1 AS ok")

    # ---------- user state ----------
    def state(self, user_id: int) -> dict:
        row = self.one("SELECT * FROM user_state WHERE user_id = ?", (user_id,))
        return dict(row) if row else {"user_id": user_id, **{f: None for f in STATE_FIELDS}, "newest_first": 0}

    def set_state(self, user_id: int, **fields) -> None:
        assert fields and set(fields) <= set(STATE_FIELDS)
        cols = ", ".join(fields)
        marks = ", ".join("?" * len(fields))
        updates = ", ".join(f"{k} = excluded.{k}" for k in fields)
        self.ex(
            f"INSERT INTO user_state (user_id, {cols}) VALUES (?, {marks})"
            f" ON CONFLICT (user_id) DO UPDATE SET {updates}",
            (user_id, *fields.values()),
        )

    def newest_first(self, user_id: int) -> bool:
        return bool(self.state(user_id)["newest_first"])

    def set_newest_first(self, user_id: int, value: bool) -> None:
        self.set_state(user_id, newest_first=int(value))

    # ---------- chat messages ----------
    def track_message(self, chat_id: int, message_id: int, grp: str | None = None) -> None:
        self.ex(
            "INSERT INTO chat_messages (chat_id, message_id, grp, sent_at) VALUES (?, ?, ?, ?)"
            " ON CONFLICT (chat_id, message_id) DO UPDATE SET grp = COALESCE(excluded.grp, chat_messages.grp)",
            (chat_id, message_id, grp, int(time.time())),
        )

    def pop_messages(self, chat_id: int, grp: str | None, since: int) -> list[int]:
        """Message ids to delete (one listing, or all when grp is None); forgets them."""
        where = "chat_id = ? AND sent_at >= ?" + (" AND grp = ?" if grp else "")
        params = [chat_id, since] + ([grp] if grp else [])
        ids = [r["message_id"] for r in self.all(f"SELECT message_id FROM chat_messages WHERE {where}", params)]
        self.ex(f"DELETE FROM chat_messages WHERE {where}", params)
        return ids

    def prune_messages(self, older_than: int) -> None:
        self.ex("DELETE FROM chat_messages WHERE sent_at < ?", (older_than,))

    # ---------- batches ----------
    def new_batch(self, user_id: int) -> int:
        return self.one(
            "INSERT INTO batches (user_id, created_at) VALUES (?, ?) RETURNING id", (user_id, int(time.time()))
        )["id"]

    def batch_circle_ids(self, user_id: int, batch_id: int) -> list[int]:
        rows = self.all("SELECT id FROM circles WHERE user_id = ? AND batch_id = ? ORDER BY id", (user_id, batch_id))
        return [r["id"] for r in rows]

    # ---------- circles ----------
    def add_circle(
        self, user_id: int, file_id: str, file_unique_id: str, duration: int | None, orig_date: int | None,
        batch_id: int, thumb_file_id: str | None = None,
    ) -> tuple[int, bool]:
        """Returns (circle_id, is_new). A circle saved before is moved into the new batch."""
        row = self.one("SELECT id FROM circles WHERE user_id = ? AND file_unique_id = ?", (user_id, file_unique_id))
        if row:
            self.ex(
                "UPDATE circles SET batch_id = ?, file_id = ?, thumb_file_id = COALESCE(?, thumb_file_id) WHERE id = ?",
                (batch_id, file_id, thumb_file_id, row["id"]),
            )
            return row["id"], False
        new = self.one(
            "INSERT INTO circles (user_id, file_id, file_unique_id, duration, orig_date, added_at, batch_id,"
            " thumb_file_id) VALUES (?, ?, ?, ?, ?, ?, ?, ?) RETURNING id",
            (user_id, file_id, file_unique_id, duration, orig_date, int(time.time()), batch_id, thumb_file_id),
        )
        return new["id"], True

    def get_circle(self, user_id: int, circle_id: int):
        return self.one("SELECT * FROM circles WHERE id = ? AND user_id = ?", (circle_id, user_id))

    def get_circles(self, user_id: int, circle_ids: list[int]) -> list:
        if not circle_ids:
            return []
        ph = ",".join("?" * len(circle_ids))
        return self.all(f"SELECT * FROM circles WHERE user_id = ? AND id IN ({ph})", [user_id, *circle_ids])

    def delete_circle(self, user_id: int, circle_id: int) -> None:
        self.ex("DELETE FROM circles WHERE id = ? AND user_id = ?", (circle_id, user_id))

    def mark_stored(self, circle_id: int, kind: str) -> None:
        col = "stored_video" if kind == "v" else "stored_thumb"
        self.ex(f"UPDATE circles SET {col} = 1 WHERE id = ?", (circle_id,))

    def circle_tag_names(self, circle_id: int) -> list[str]:
        rows = self.all(
            "SELECT t.name FROM tags t JOIN circle_tags ct ON ct.tag_id = t.id WHERE ct.circle_id = ? ORDER BY t.name",
            (circle_id,),
        )
        return [r["name"] for r in rows]

    def find_circles(
        self, user_id: int, tag_ids: list[int] | None, untagged: bool = False,
        offset: int = 0, limit: int = 10, newest_first: bool = False,
    ) -> tuple[list, int]:
        """Circles that have ALL given tags (None = all circles). Returns (page, total)."""
        if untagged:
            where = "c.user_id = ? AND NOT EXISTS (SELECT 1 FROM circle_tags ct WHERE ct.circle_id = c.id)"
            params: list = [user_id]
        elif tag_ids:
            ph = ",".join("?" * len(tag_ids))
            where = (
                f"c.user_id = ? AND c.id IN (SELECT circle_id FROM circle_tags WHERE tag_id IN ({ph})"
                f" GROUP BY circle_id HAVING COUNT(DISTINCT tag_id) = ?)"
            )
            params = [user_id, *tag_ids, len(tag_ids)]
        else:
            where = "c.user_id = ?"
            params = [user_id]
        total = self.one(f"SELECT COUNT(*) AS n FROM circles c WHERE {where}", params)["n"]
        d = "DESC" if newest_first else "ASC"
        rows = self.all(
            f"SELECT c.* FROM circles c WHERE {where}"
            f" ORDER BY COALESCE(c.orig_date, c.added_at) {d}, c.id {d} LIMIT ? OFFSET ?",
            [*params, limit, offset],
        )
        return rows, total

    def count_circles(self, user_id: int) -> tuple[int, int]:
        """(total, untagged)."""
        total = self.one("SELECT COUNT(*) AS n FROM circles WHERE user_id = ?", (user_id,))["n"]
        untagged = self.one(
            "SELECT COUNT(*) AS n FROM circles c WHERE c.user_id = ?"
            " AND NOT EXISTS (SELECT 1 FROM circle_tags ct WHERE ct.circle_id = c.id)",
            (user_id,),
        )["n"]
        return total, untagged

    # ---------- gallery ----------
    def gallery_circles(self, user_id: int) -> list[dict]:
        """Every circle with its tag names, oldest first (the client re-sorts)."""
        rows = self.all(
            "SELECT id, duration, COALESCE(orig_date, added_at) AS date, thumb_file_id FROM circles"
            " WHERE user_id = ? ORDER BY date, id",
            (user_id,),
        )
        pairs = self.all(
            "SELECT ct.circle_id, t.name FROM circle_tags ct JOIN tags t ON t.id = ct.tag_id WHERE t.user_id = ?",
            (user_id,),
        )
        names: dict[int, list[str]] = {}
        for p in pairs:
            names.setdefault(p["circle_id"], []).append(p["name"])
        return [
            {
                "id": r["id"],
                "date": r["date"],
                "duration": r["duration"] or 0,
                "has_thumb": r["thumb_file_id"] is not None,
                "tags": sorted(names.get(r["id"], [])),
            }
            for r in rows
        ]

    def set_circle_tags(self, user_id: int, circle_id: int, names: list[str]) -> list[str]:
        """Replace a circle's tags with exactly `names` (creating missing tags)."""
        ids = [tid for tid in (self.get_or_create_tag(user_id, n) for n in names) if tid]
        self.ex("DELETE FROM circle_tags WHERE circle_id = ?", (circle_id,))
        self.add_tag_to([circle_id], ids)
        return self.circle_tag_names(circle_id)

    # ---------- tags ----------
    def get_or_create_tag(self, user_id: int, name: str) -> int | None:
        name = normalize_tag(name)
        if not name:
            return None
        self.ex("INSERT INTO tags (user_id, name) VALUES (?, ?) ON CONFLICT (user_id, name) DO NOTHING", (user_id, name))
        return self.one("SELECT id FROM tags WHERE user_id = ? AND name = ?", (user_id, name))["id"]

    def find_tag(self, user_id: int, name: str):
        return self.one("SELECT * FROM tags WHERE user_id = ? AND name = ?", (user_id, normalize_tag(name)))

    def get_tag(self, user_id: int, tag_id: int):
        return self.one("SELECT * FROM tags WHERE id = ? AND user_id = ?", (tag_id, user_id))

    def list_tags(self, user_id: int) -> list:
        """All tags with circle counts, most used first."""
        return self.all(
            "SELECT t.id, t.name, COUNT(ct.circle_id) AS cnt FROM tags t"
            " LEFT JOIN circle_tags ct ON ct.tag_id = t.id"
            " WHERE t.user_id = ? GROUP BY t.id, t.name ORDER BY cnt DESC, t.name",
            (user_id,),
        )

    def rename_tag(self, user_id: int, tag_id: int, new_name: str) -> bool:
        """Renames; if a tag with new_name exists, merges into it. Returns False on bad name."""
        new_name = normalize_tag(new_name)
        if not new_name:
            return False
        existing = self.find_tag(user_id, new_name)
        if existing and existing["id"] != tag_id:
            self.ex(
                "INSERT INTO circle_tags (circle_id, tag_id) SELECT circle_id, ? FROM circle_tags WHERE tag_id = ?"
                " ON CONFLICT (circle_id, tag_id) DO NOTHING",
                (existing["id"], tag_id),
            )
            self.ex("DELETE FROM tags WHERE id = ?", (tag_id,))
        else:
            self.ex("UPDATE tags SET name = ? WHERE id = ? AND user_id = ?", (new_name, tag_id, user_id))
        return True

    def delete_tag(self, user_id: int, tag_id: int) -> None:
        self.ex("DELETE FROM tags WHERE id = ? AND user_id = ?", (tag_id, user_id))

    # ---------- tagging ----------
    def add_tag_to(self, circle_ids: list[int], tag_ids: int | list[int]) -> None:
        tag_ids = [tag_ids] if isinstance(tag_ids, int) else tag_ids
        self.many(
            "INSERT INTO circle_tags (circle_id, tag_id) VALUES (?, ?) ON CONFLICT (circle_id, tag_id) DO NOTHING",
            [(c, t) for c in circle_ids for t in tag_ids],
        )

    def remove_tag_from(self, circle_ids: list[int], tag_id: int) -> None:
        self.many("DELETE FROM circle_tags WHERE circle_id = ? AND tag_id = ?", [(c, tag_id) for c in circle_ids])

    def tags_on_all(self, circle_ids: list[int]) -> set[int]:
        """Tag ids that are set on every one of the given circles."""
        if not circle_ids:
            return set()
        ph = ",".join("?" * len(circle_ids))
        rows = self.all(
            f"SELECT tag_id FROM circle_tags WHERE circle_id IN ({ph}) GROUP BY tag_id HAVING COUNT(*) = ?",
            [*circle_ids, len(circle_ids)],
        )
        return {r["tag_id"] for r in rows}
